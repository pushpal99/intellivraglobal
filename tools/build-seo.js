#!/usr/bin/env node
/**
 * build-seo.js - Intellivra Global
 *
 * Regenerates sitemap.xml and llms.txt from the pages on disk plus
 * config/site.config.json, so contact details never have to be typed twice.
 *
 *   node tools/build-seo.js            # write sitemap.xml + llms.txt
 *   node tools/build-seo.js --check    # exit 1 if either file is stale (CI)
 *
 * Pages carrying `noindex` are skipped in the sitemap automatically. lastmod
 * comes from each file's modification time, so committing an edit updates it.
 */

'use strict';

const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const CHECK = process.argv.includes('--check');
const cfg = JSON.parse(fs.readFileSync(path.join(ROOT, 'config', 'site.config.json'), 'utf8'));
const BASE = String(cfg.site.url).replace(/\/+$/, '');

/** Sitemap priority and change frequency by page. */
const WEIGHTS = {
  'index.html': { priority: '1.0', changefreq: 'weekly' },
  'services.html': { priority: '0.9', changefreq: 'monthly' },
  'industries.html': { priority: '0.8', changefreq: 'monthly' },
  'careers.html': { priority: '0.8', changefreq: 'daily' },
  'contact.html': { priority: '0.7', changefreq: 'monthly' },
  'about.html': { priority: '0.6', changefreq: 'monthly' },
};

function readPages() {
  return fs
    .readdirSync(ROOT)
    .filter((f) => f.endsWith('.html'))
    .map((file) => {
      const html = fs.readFileSync(path.join(ROOT, file), 'utf8');
      const pick = (re) => {
        const m = html.match(re);
        return m ? m[1].replace(/\s+/g, ' ').trim() : '';
      };
      return {
        file,
        title: pick(/<title>([\s\S]*?)<\/title>/i),
        description: pick(/<meta name="description" content="([^"]*)"/i),
        canonical: pick(/<link rel="canonical" href="([^"]*)"/i),
        noindex: /content="noindex/i.test(html),
        lastmod: fs.statSync(path.join(ROOT, file)).mtime.toISOString().slice(0, 10),
      };
    })
    .sort((a, b) => {
      const order = Object.keys(WEIGHTS);
      return (order.indexOf(a.file) + 1 || 99) - (order.indexOf(b.file) + 1 || 99);
    });
}

function buildSitemap(pages) {
  const entries = pages
    .filter((p) => !p.noindex && p.canonical)
    .map((p) => {
      const weight = WEIGHTS[p.file] || { priority: '0.5', changefreq: 'monthly' };
      const loc = p.file === 'index.html' ? `${BASE}/` : p.canonical;
      return [
        '  <url>',
        `    <loc>${loc}</loc>`,
        `    <lastmod>${p.lastmod}</lastmod>`,
        `    <changefreq>${weight.changefreq}</changefreq>`,
        `    <priority>${weight.priority}</priority>`,
        '  </url>',
      ].join('\n');
    });

  return [
    '<?xml version="1.0" encoding="UTF-8"?>',
    '<!-- Generated by tools/build-seo.js - run it after adding or renaming a page. -->',
    '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">',
    entries.join('\n'),
    '</urlset>',
    '',
  ].join('\n');
}

