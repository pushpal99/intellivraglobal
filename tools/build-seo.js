function writeOrCheck(file, content) {
  const target = path.join(ROOT, file);
  const current = fs.existsSync(target) ? fs.readFileSync(target, 'utf8') : null;
  // llms.txt carries a generated date; ignore it when checking staleness.
  const normalise = (text) => (text || '').replace(/^Last updated: .*$/m, '');

  if (normalise(current) === normalise(content)) {
    console.log(`  ok      ${file}`);
    return 0;
  }
  if (CHECK) {
    console.error(`  STALE   ${file}`);
    return 1;
  }
  fs.writeFileSync(target, content, 'utf8');
  console.log(`  written ${file}`);
  return 0;
}

const pages = readPages();
let stale = 0;
stale += writeOrCheck('sitemap.xml', buildSitemap(pages));
stale += writeOrCheck('llms.txt', buildLlmsTxt(pages));

if (CHECK && stale) {
  console.error('\nRun: node tools/build-seo.js');
  process.exit(1);
}
